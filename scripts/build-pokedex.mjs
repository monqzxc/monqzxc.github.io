// Writes lib/pokemon-dex.ts: the National Pokédex number and current types of every habitat
// resident, from PokeAPI's open data (default form of each species). Re-run after adding residents.
//
//   node --experimental-strip-types scripts/build-pokedex.mjs
import { writeFileSync } from "node:fs";
import { SPECIES } from "../lib/pokemon-roster.ts";

const BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv";

async function csv(name) {
  const response = await fetch(`${BASE}/${name}.csv`, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`${response.status} for ${name}.csv`);
  const [header, ...rows] = (await response.text()).trim().split("\n").map(line => line.split(","));
  return rows.map(row => Object.fromEntries(header.map((key, index) => [key, row[index]])));
}

const [species, pokemon, pokemonTypes, types] = await Promise.all(["pokemon_species", "pokemon", "pokemon_types", "types"].map(csv));
const speciesId = new Map(species.map(row => [row.identifier, Number(row.id)]));
const defaultForm = new Map(pokemon.filter(row => row.is_default === "1").map(row => [Number(row.species_id), row.id]));
const typeName = new Map(types.map(row => [row.id, row.identifier]));
const typesOf = new Map();
for (const row of pokemonTypes.sort((a, b) => a.slot - b.slot)) typesOf.set(row.pokemon_id, [...(typesOf.get(row.pokemon_id) ?? []), typeName.get(row.type_id)]);

const lines = [];
for (const key of Object.keys(SPECIES)) {
  const no = speciesId.get(key.replace(/_/g, "-"));
  if (!no) throw new Error(`no PokeAPI species for ${key}`);
  const entryTypes = typesOf.get(defaultForm.get(no));
  if (!entryTypes?.length) throw new Error(`no types for ${key}`);
  lines.push(`  ${key}: { no: ${no}, types: [${entryTypes.map(type => `"${type}"`).join(", ")}] },`);
}

writeFileSync(new URL("../lib/pokemon-dex.ts", import.meta.url), `// Generated by scripts/build-pokedex.mjs from PokeAPI data. Do not edit by hand.
import type { PokemonSpecies } from "./pokemon-roster.ts";

export type PokemonType =
  | "normal" | "fire" | "water" | "electric" | "grass" | "ice" | "fighting" | "poison" | "ground"
  | "flying" | "psychic" | "bug" | "rock" | "ghost" | "dragon" | "dark" | "steel" | "fairy";

export type DexEntry = { no: number; types: [PokemonType] | [PokemonType, PokemonType] };

/** National Pokédex number and types (default form). */
export const DEX: Record<PokemonSpecies, DexEntry> = {
${lines.join("\n")}
};
`);
console.log(`Wrote ${lines.length} Pokédex entries.`);
